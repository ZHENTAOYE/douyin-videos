# 送进 TTS 前的读音修正（左：字幕原文，右：实际朗读）
SAY_FIX = [
    ("90年代", "九十年代"),
    ("系住", "记住"),          # 系 jì，词典默认读 xì
]


def plain(text):
    return text.replace("【", "").replace("】", "")


def say_text(text):
    s = plain(text)
    for a, b in SAY_FIX:
        s = s.replace(a, b)
    return s


if __name__ == "__main__":
    total = 0
    for sid, scene, text, pause in SEGMENTS:
        n = len(plain(text))
        total += n
        print(f"{sid:3s} {scene:12s} {n:3d} {say_text(text)}")
    print("chars:", total, "segments:", len(SEGMENTS))
