# 送进 TTS 前的读音修正（左：字幕原文，右：实际朗读）
SAY_FIX = [
    ("26.2%", "百分之二十六点二"),
    ("15.3%", "百分之十五点三"),
    ("ChatGPT上线", "恰特G-P-T上线"),
    ("好景不长", "好景不常"),
    ("ImageNet", "Image-Net"),
    ("AlphaGo 4比1", "阿尔法狗，四比一"),
    ("DeepMind", "Deep Mind"),
    ("沃尔特·皮茨", "沃尔特，皮茨"),
    ("8层", "八层"),
    ("4400万美元", "四千四百万美元"),
    ("2018年度", "2018年度的"),
]


def plain(text):
    return text.replace("【", "").replace("】", "")


def say_text(text):
    s = plain(text)
    for a, b in SAY_FIX:
        s = s.replace(a, b)
    return s


